function withDetails(
  base: Omit<
    Product,
    | "fullDescription"
    | "productType"
    | "productKind"
    | "useEnvironment"
    | "material"
    | "dimensions"
    | "features"
    | "limitations"
  >,
  details: Details,
): Product {
  const [
    productType,
    useEnvironment,
    material,
    dimensions,
    features,
    limitations,
  ] = details;
  const type = productTypes[productType];
  if (!type) throw new Error(`Unknown product type: ${productType}`);
  return {
    ...base,
    productType,
    productKind: type.kind,
    useEnvironment,
    material,
    dimensions,
    features,
    limitations,
    fullDescription: `${base.description} Made from ${material}, it measures ${dimensions}. Features: ${features.join(", ")}. ${limitations.join(". ")}.`,
  };
}

export const products: Product[] = [
  ...existingProducts.map((product) => {
    const details = existingDetails[product.id];
    if (!details) throw new Error(`Missing catalog details: ${product.id}`);
    return withDetails(product, details);
  }),
  ...additions.map(
    ([
      id,
      name,
      category,
      price,
      productType,
      useEnvironment,
      material,
      dimensions,
      features,
      limitations,
      description,
    ]) =>
      withDetails(
        {
          id,
          name,
          category,
          price,
          description,
          currency: "EUR",
          inStock: true,
          imageUrl: `/images/products/${id}.webp`,
          productUrl: `/products/${id}`,
        },
        [
          productType,
          useEnvironment,
          material,
          dimensions,
          features,
          limitations,
        ],
      ),
  ),
];
